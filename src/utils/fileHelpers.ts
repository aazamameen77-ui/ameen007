import { FileType } from '../types';

export function getFileTypeFromExtension(extension: string): FileType {
  const ext = extension.toLowerCase().replace('.', '');
  
  const imageExts = ['jpg', 'jpeg', 'png', 'gif', 'webp', 'svg', 'bmp', 'ico'];
  if (imageExts.includes(ext)) return 'image';

  const docExts = ['pdf', 'doc', 'docx', 'txt', 'rtf', 'odt', 'md'];
  if (docExts.includes(ext)) return 'document';

  const sheetExts = ['xls', 'xlsx', 'csv', 'ods', 'tsv'];
  if (sheetExts.includes(ext)) return 'spreadsheet';

  const presExts = ['ppt', 'pptx', 'key', 'odp'];
  if (presExts.includes(ext)) return 'presentation';

  const videoExts = ['mp4', 'mov', 'avi', 'mkv', 'webm', 'wmv'];
  if (videoExts.includes(ext)) return 'video';

  const audioExts = ['mp3', 'wav', 'ogg', 'm4a', 'flac', 'aac'];
  if (audioExts.includes(ext)) return 'audio';

  const codeExts = ['js', 'ts', 'jsx', 'tsx', 'html', 'css', 'json', 'py', 'go', 'rs', 'java', 'c', 'cpp', 'sh', 'sql', 'yaml', 'yml'];
  if (codeExts.includes(ext)) return 'code';

  const archiveExts = ['zip', 'rar', '7z', 'tar', 'gz', 'bz2'];
  if (archiveExts.includes(ext)) return 'archive';

  return 'other';
}

