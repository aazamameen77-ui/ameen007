export function downloadFile(filename: string, contentUrlOrText?: string, mimeType: string = 'text/plain') {
  if (contentUrlOrText && (contentUrlOrText.startsWith('data:') || contentUrlOrText.startsWith('blob:') || contentUrlOrText.startsWith('http'))) {
    const a = document.createElement('a');
    a.href = contentUrlOrText;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  } else {
    // Generate text/blob download
    const content = contentUrlOrText || `File content for ${filename} - generated by CloudVault`;
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  }
}

export function generateRandomId(prefix: string = 'item'): string {
  return `${prefix}_${Math.random().toString(36).substring(2, 9)}_${Date.now().toString(36)}`;
}
